// pgmCase 描述一个 PGM 测试样本。
type pgmCase struct {
	name    string
	data    []byte
	want    []uint8 // 期望的 8 位灰度像素（逐像素）
	wantErr bool
}

// buildPGM5 生成一个 P5（二进制）PGM。
func buildPGM5(w, h, maxv int, pixels []byte, comment string) []byte {
	var buf bytes.Buffer
	buf.WriteString("P5\n")
	if comment != "" {
		buf.WriteString("# " + comment + "\n")
	}
	buf.WriteString(itoa(w) + " " + itoa(h) + "\n")
	buf.WriteString(itoa(maxv) + "\n")
	buf.Write(pixels)
	return buf.Bytes()
}

// buildPGM2 生成一个 P2（ASCII）PGM。
func buildPGM2(w, h, maxv int, values []int, comment string) []byte {
	var buf bytes.Buffer
	buf.WriteString("P2\n")
	if comment != "" {
		buf.WriteString("# " + comment + "\n")
	}
	buf.WriteString(itoa(w) + " " + itoa(h) + "\n")
	buf.WriteString(itoa(maxv) + "\n")
	for i, v := range values {
		if i > 0 {
			buf.WriteByte(' ')
		}
		buf.WriteString(itoa(v))
	}
	buf.WriteByte('\n')
	return buf.Bytes()
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	neg := n < 0
	if neg {
		n = -n
	}
	var b [20]byte
	i := len(b)
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	if neg {
		i--
		b[i] = '-'
	}
	return string(b[i:])
}

// TestDecodePGMNormalization 覆盖 P2/P5、8/16 位、不同 maxval、注释。
//
// 重点回归：maxv=15 的 8 位 P5 必须按 maxv 归一化（15 → 255），
// 网页版 docs/tools/mapview.html 曾直接拷贝原始像素导致整张图偏暗。
func TestDecodePGMNormalization(t *testing.T) {
	cases := []pgmCase{
		{
			name: "P5 maxv=255 原样",
			data: buildPGM5(2, 1, 255, []byte{0, 255}, ""),
			want: []uint8{0, 255},
		},
		{
			name: "P5 maxv=15 归一化",
			data: buildPGM5(3, 1, 15, []byte{0, 8, 15}, ""),
			want: []uint8{0, 136, 255}, // 8*255/15 = 136
		},
		{
			name: "P5 maxv=1 只有黑白",
			data: buildPGM5(2, 1, 1, []byte{0, 1}, ""),
			want: []uint8{0, 255},
		},
		{
			name: "P5 maxv=15 带注释",
			data: buildPGM5(3, 1, 15, []byte{0, 8, 15}, "generated by slam"),
			want: []uint8{0, 136, 255},
		},
		{
			name: "P2 maxv=255 原样",
			data: buildPGM2(3, 1, 255, []int{0, 128, 255}, ""),
			want: []uint8{0, 128, 255},
		},
		{
			name: "P2 maxv=15 归一化",
			data: buildPGM2(3, 1, 15, []int{0, 8, 15}, ""),
			want: []uint8{0, 136, 255},
		},
		{
			name: "P2 多行 + 注释",
			data: buildPGM2(2, 2, 15, []int{0, 8, 15, 3}, "注释一行"),
			want: []uint8{0, 136, 255, 51}, // 3*255/15 = 51
		},
		{
			name: "P5 16bit 大端 maxv=65535",
			data: buildPGM5(2, 1, 65535, []byte{0x00, 0x00, 0xff, 0xff}, ""),
			want: []uint8{0, 255},
		},
		{
			name: "P5 16bit 大端 maxv=1000",
			data: buildPGM5(2, 1, 1000, []byte{0x00, 0x00, 0x03, 0xe8}, ""),
			want: []uint8{0, 255}, // 1000 → 255
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			img, err := DecodePGM(tc.data)
			if err != nil {
				t.Fatalf("DecodePGM: %v", err)
			}
			if len(img.Pix) != len(tc.want) {
				t.Fatalf("pixels = %d, want %d", len(img.Pix), len(tc.want))
			}
			for i := range tc.want {
				if img.Pix[i] != tc.want[i] {
					t.Errorf("pixel[%d] = %d, want %d (all: %v)", i, img.Pix[i], tc.want[i], img.Pix)
				}
			}
		})
	}
}

// TestDecodePGMErrors 覆盖异常文件。
func TestDecodePGMErrors(t *testing.T) {
	cases := map[string][]byte{
		"空文件":       {},
		"未知魔数":      []byte("P3\n1 1\n255\n0\n"),
		"尺寸为 0":     []byte("P5\n0 0\n255\n"),
		"maxv 为 0":  []byte("P5\n1 1\n0\n"),
		"数据不足":      []byte("P5\n4 4\n255\nshort"),
		"maxv 超过上限": []byte("P5\n1 1\n70000\n\x00"),
		"P2 数据不足":   []byte("P2\n2 2\n255\n1 2"),
	}
	for name, data := range cases {
		t.Run(name, func(t *testing.T) {
			if _, err := DecodePGM(data); err == nil {
				t.Fatal("expected error")
			}
		})
	}
}

// TestPGMSamplesOnDisk 校验仓库内共享的测试样本（网页端测试用同一批文件）。
func TestPGMSamplesOnDisk(t *testing.T) {
	dir := filepath.Join("..", "..", "tests", "data")
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Skipf("共享样本目录不存在: %v", err)
	}
	for _, e := range entries {
		if e.IsDir() || filepath.Ext(e.Name()) != ".pgm" {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			t.Fatalf("读取 %s: %v", e.Name(), err)
		}
		if _, err := DecodePGM(raw); err != nil {
			t.Errorf("%s 解析失败: %v", e.Name(), err)
		}
	}
}
